/** A reference-data entry as carried in the bundled snapshot. Fields beyond ID/Title are category-specific. */
export interface ReferenceEntry {
  /** Free-text comments (charge levels). */
  readonly Comments?: string | null;
  /** Continent code (countries). */
  readonly ContinentCode?: string | null;
  /** Current type description. */
  readonly Description?: string | null;
  /** Formal/standard name (connection types). null when none. */
  readonly FormalName?: string | null;
  /** Numeric OCM reference ID — the value POI filters key on. */
  readonly ID: number;
  /** ISO 3166-1 alpha-2 code (countries). */
  readonly ISOCode?: string;
  /** Usage type: physical access key required. null when unknown. */
  readonly IsAccessKeyRequired?: boolean | null;
  /** Whether the connector type is discontinued. null when unknown. */
  readonly IsDiscontinued?: boolean | null;
  /** Charge level: fast-charge capable. */
  readonly IsFastChargeCapable?: boolean | null;
  /** Usage type: membership/RFID required. null when unknown. */
  readonly IsMembershipRequired?: boolean | null;
  /** Whether the connector type is obsolete. null when unknown. */
  readonly IsObsolete?: boolean | null;
  /** Status type: whether it counts as operational. null/absent for Unknown (ID 0). */
  readonly IsOperational?: boolean | null;
  /** Usage type: payment required at location. null when unknown. */
  readonly IsPayAtLocation?: boolean | null;
  /** Human-readable title. */
  readonly Title: string;
  /** Operator website. null when none. */
  readonly WebsiteURL?: string | null;
}

/** Bundled OCM reference snapshot, keyed by category. */
export interface ReferenceSnapshot {
  readonly connectiontypes: readonly ReferenceEntry[];
  readonly countries: readonly ReferenceEntry[];
  readonly currenttypes: readonly ReferenceEntry[];
  readonly levels: readonly ReferenceEntry[];
  readonly operators: readonly ReferenceEntry[];
  readonly statustypes: readonly ReferenceEntry[];
  readonly usagetypes: readonly ReferenceEntry[];
}

